// WriteTheme writes the Keycloak login theme for b into dir: the file set
// measured in docs/lab write-up 13 on Keycloak 26.3 (parent keycloak.v2).
// Files are written atomically (temp file, rename) with mode 0644; a logo
// of another type left by a previous save is removed. The tab icon goes
// in as img/favicon.ico, the file keycloak.v2's template links.
func WriteTheme(dir string, b Branding) error {
	for _, d := range []string{"login", "login/resources/css", "login/resources/img", "login/messages"} {
		if err := os.MkdirAll(filepath.Join(dir, d), 0o755); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	files := map[string]string{
		"login/theme.properties":                themeProperties,
		"login/resources/css/portico.css":       themeCSS(b),
		"login/messages/messages_en.properties": themeMessages(b),
		"login/resources/img/portico-mark.svg":  PorticoMark("#ffffff"),
	}
	for rel, content := range files {
		if err := writeAtomic(filepath.Join(dir, rel), []byte(content)); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	// keycloak.v2's template links img/favicon.ico: the tenant icon.
	icons, err := TenantIcons(b)
	if err != nil {
		return fmt.Errorf("theme: %w", err)
	}
	if err := writeAtomic(filepath.Join(dir, "login/resources/img/favicon.ico"), icons.ICO); err != nil {
		return fmt.Errorf("theme: %s: %w", dir, err)
	}
	// One logo file at most, named by type.
	for _, ext := range []string{"png", "jpg", "svg"} {
		p := filepath.Join(dir, "login/resources/img/logo."+ext)
		if b.HasLogo() && ext == b.LogoExt() {
			if err := writeAtomic(p, b.LogoData); err != nil {
				return fmt.Errorf("theme: %s: %w", dir, err)
			}
			continue
		}
		if err := os.Remove(p); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	return nil
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o644); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}

// styles lists the parent's base sheet first: keycloak.v2 on Keycloak
// 26.3 ships css/styles.css (css/login.css of older releases is gone, 404
// on the lab, so the parent's styles were not loaded until this line).
const themeProperties = `parent=keycloak.v2
import=common/keycloak
styles=css/styles.css css/portico.css
`

// themeCSS restyles the keycloak.v2 login page (PatternFly 5 markup
// measured on the lab: body#keycloak-bg, .pf-v5-c-login__container with
// header#kc-header and main.pf-v5-c-login__main) as one centred column on
// the accent colour: the lockup (logo left of the MSP name, white, Red
// Hat Display, last word bold) above the card, "Powered by Portico" under
// it. keycloak.v2 lays the header beside the card and paints the page
// with its own background image; both are overridden here.
func themeCSS(b Branding) string {
	var sb strings.Builder
	sb.WriteString("/* Generated by Portico from the branding settings. */\n")
	fmt.Fprintf(&sb, ":root { --portico-accent: %s; }\n", b.AccentColor)
	sb.WriteString("body#keycloak-bg { background: var(--portico-accent); }\n")
	sb.WriteString(".pf-v5-c-login { background: none; }\n")
	sb.WriteString(".pf-v5-c-login__container { display: flex; flex-direction: column; align-items: center; gap: 1.5rem; width: 100%; max-width: none; padding: 8vh 1rem 3rem; }\n")
	sb.WriteString("#kc-header { order: 0; grid-area: auto; width: auto; }\n")
	// align-self: PatternFly starts the card at the cross-axis start,
	// which in a column is the left edge; the parent theme's blue 4 px
	// band on the card header goes too.
	sb.WriteString(".pf-v5-c-login__main { order: 1; grid-area: auto; align-self: center; width: 100%; max-width: 480px; margin: 0; border-radius: 14px; overflow: hidden; box-shadow: 0 12px 32px rgba(0, 0, 0, 0.28); }\n")
	sb.WriteString(".pf-v5-c-login__main-header { border-top: 0; }\n")
	// The header is a column: the lockup (mark as tall as the capitals,
	// name in uppercase, last word bold) and the claim under it.
	sb.WriteString("#kc-header-wrapper { display: flex; flex-direction: column; align-items: center; gap: 0.7rem; padding: 0; text-transform: none; letter-spacing: normal; color: #fff; font-family: \"RedHatDisplay\", \"Helvetica Neue\", Arial, sans-serif; font-weight: 300; }\n")
	sb.WriteString(".portico-lockup { display: flex; align-items: center; gap: 0.6em; font-size: 2.25rem; line-height: 1; text-transform: uppercase; letter-spacing: 0.08em; }\n")
	sb.WriteString(".portico-lockup strong { font-weight: 700; }\n")
	sb.WriteString(".portico-claim { font-size: 1.05rem; font-weight: 400; opacity: 0.9; }\n")
	if b.HasLogo() {
		// A generated block in the flex row sits left of the name, one
		// em tall (the mark is 600 by 680); the logo is a background so
		// any image type works (write-up 13).
		fmt.Fprintf(&sb, ".portico-lockup::before { content: \"\"; width: 0.88em; height: 1em; flex: none; background: url(../img/logo.%s) no-repeat center; background-size: contain; }\n", b.LogoExt())
	}
	sb.WriteString(".pf-v5-c-login__container::after { content: \"Powered by Portico\"; order: 2; margin-top: 1.5rem; color: #fff; opacity: 0.75; font-size: 0.8rem; padding-left: 1.4rem; background: url(../img/portico-mark.svg) no-repeat left center; background-size: contain; line-height: 1.2rem; }\n")
	sb.WriteString(".pf-v5-c-button.pf-m-primary { background-color: var(--portico-accent); border-color: var(--portico-accent); border-radius: 8px; }\n")
	sb.WriteString(".pf-v5-c-button.pf-m-primary:hover { filter: brightness(1.1); }\n")
	sb.WriteString(".pf-v5-c-form-control { border-radius: 8px; }\n")
	sb.WriteString("a, .pf-v5-c-button.pf-m-link { color: var(--portico-accent); }\n")
	return sb.String()
}

// themeMessages sets the texts of the login page. loginTitleHtml renders
// HTML: it carries the lockup (the MSP name, last word bold) and, under
// it, the tagline as the claim; every piece is HTML-escaped and then
// escaped for the properties syntax. The card itself says "Sign in".
func themeMessages(b Branding) string {
	name := strings.TrimSpace(b.MSPName)
	lockup := html.EscapeString(name)
	if i := strings.LastIndex(name, " "); i > 0 {
		// A wordmark: no space before the bold last word (PORTICO**MSP**).
		lockup = html.EscapeString(name[:i]) + "<strong>" + html.EscapeString(strings.TrimSpace(name[i+1:])) + "</strong>"
	}
	title := `<span class="portico-lockup"><span class="portico-name">` + lockup + `</span></span>`
	if claim := strings.TrimSpace(b.Tagline); claim != "" {
		title += `<span class="portico-claim">` + html.EscapeString(claim) + `</span>`
	}
	return "loginTitleHtml=" + PropertiesEscape(title) + "\n" + "loginAccountTitle=Sign in\n"
}

// PropertiesEscape escapes a value for a Java .properties file: backslash,
// newline, carriage return, tab, leading spaces, "=", ":" and "#" are
// escaped; non-ASCII stays (Keycloak reads UTF-8).
func PropertiesEscape(s string) string {
	var sb strings.Builder
	for i, r := range s {
		switch r {
		case '\\':
			sb.WriteString(`\\`)
		case '\n':
			sb.WriteString(`\n`)
		case '\r':
			sb.WriteString(`\r`)
		case '\t':
			sb.WriteString(`\t`)
		case '=', ':', '#', '!':
			sb.WriteByte('\\')
			sb.WriteRune(r)
		case ' ':
			if i == 0 || strings.TrimSpace(s[:i]) == "" {
				sb.WriteString(`\ `)
			} else {
				sb.WriteByte(' ')
			}
		default:
			sb.WriteRune(r)
		}
	}
	return sb.String()
}
