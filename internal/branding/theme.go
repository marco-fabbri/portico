// WriteTheme writes the Keycloak login theme for b into dir: the file set
// measured in docs/lab write-up 13 on Keycloak 26.3 (parent keycloak.v2).
// Files are written atomically (temp file, rename) with mode 0644; a logo
// of another type left by a previous save is removed.
func WriteTheme(dir string, b Branding) error {
	for _, d := range []string{"login", "login/resources/css", "login/resources/img", "login/messages"} {
		if err := os.MkdirAll(filepath.Join(dir, d), 0o755); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	files := map[string]string{
		"login/theme.properties":                themeProperties,
		"login/resources/css/portico.css":       themeCSS(b),
		"login/messages/messages_en.properties": themeMessages(b),
		"login/resources/img/portico-mark.svg":  PorticoMark("#ffffff"),
	}
	for rel, content := range files {
		if err := writeAtomic(filepath.Join(dir, rel), []byte(content)); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	// One logo file at most, named by type.
	for _, ext := range []string{"png", "jpg", "svg"} {
		p := filepath.Join(dir, "login/resources/img/logo."+ext)
		if b.HasLogo() && ext == b.LogoExt() {
			if err := writeAtomic(p, b.LogoData); err != nil {
				return fmt.Errorf("theme: %s: %w", dir, err)
			}
			continue
		}
		if err := os.Remove(p); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	return nil
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o644); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}

// styles lists the parent's base sheet first: keycloak.v2 on Keycloak
// 26.3 ships css/styles.css (css/login.css of older releases is gone, 404
// on the lab, so the parent's styles were not loaded until this line).
