// WriteTheme writes the Keycloak login theme for b into dir: the file set
// measured in docs/lab write-up 13 on Keycloak 26.3 (parent keycloak.v2).
// Files are written atomically (temp file, rename) with mode 0644; a logo
// of another type left by a previous save is removed. The tab icon goes
// in as img/favicon.ico, the file keycloak.v2's template links.
func WriteTheme(dir string, b Branding) error {
	// Keycloak's own user reads the theme inside its container: every
	// directory is made world-readable explicitly, since MkdirAll is
	// subject to the service's umask (0077 on the appliance).
	for _, d := range []string{"", "login", "login/resources", "login/resources/css", "login/resources/img", "login/messages"} {
		p := filepath.Join(dir, d)
		if err := os.MkdirAll(p, 0o755); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
		if err := os.Chmod(p, 0o755); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	files := map[string]string{
		"login/theme.properties":                themeProperties,
		"login/resources/css/portico.css":       themeCSS(b),
		"login/messages/messages_en.properties": themeMessages(b),
		"login/resources/img/portico-mark.svg":  PorticoMark(b.TextColor),
	}
	for rel, content := range files {
		if err := writeAtomic(filepath.Join(dir, rel), []byte(content)); err != nil {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	// keycloak.v2's template links img/favicon.ico: the tenant icon.
	icons, err := TenantIcons(b)
	if err != nil {
		return fmt.Errorf("theme: %w", err)
	}
	if err := writeAtomic(filepath.Join(dir, "login/resources/img/favicon.ico"), icons.ICO); err != nil {
		return fmt.Errorf("theme: %s: %w", dir, err)
	}
	// One logo file at most, named by type: the upload or the arch.
	logo, _, hasLogo := b.LogoFile()
	for _, ext := range []string{"png", "jpg", "svg"} {
		p := filepath.Join(dir, "login/resources/img/logo."+ext)
		if hasLogo && ext == b.LogoFileExt() {
			if err := writeAtomic(p, logo); err != nil {
				return fmt.Errorf("theme: %s: %w", dir, err)
			}
			continue
		}
		if err := os.Remove(p); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("theme: %s: %w", dir, err)
		}
	}
	return nil
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o644); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}

// styles lists the parent's base sheet first: keycloak.v2 on Keycloak
// 26.3 ships css/styles.css (css/login.css of older releases is gone, 404
// on Keycloak 26.3, so the parent's styles were not loaded until this line).
const themeProperties = `parent=keycloak.v2
import=common/keycloak
styles=css/styles.css css/portico.css
`

// themeCSS restyles the keycloak.v2 login page (PatternFly 5 markup
// measured on Keycloak 26.3: body#keycloak-bg, .pf-v5-c-login__container with
// header#kc-header and main.pf-v5-c-login__main) as one centred column on
// the background colour: the header (logo, text, claim, in the text
// colour, Red Hat Display) above the card, "Powered by Portico" under it
// (design branding §4.2). keycloak.v2 lays the header beside the card and
// paints the page with its own background image; both are overridden.
func themeCSS(b Branding) string {
	var sb strings.Builder
	sb.WriteString("/* Generated by Portico from the branding settings. */\n")
	fmt.Fprintf(&sb, ":root { --portico-bg: %s; --portico-text: %s; --portico-accent: %s; }\n", b.BackgroundColor, b.TextColor, b.AccentColor)
	sb.WriteString("body#keycloak-bg { background: var(--portico-bg); }\n")
	sb.WriteString(".pf-v5-c-login { background: none; }\n")
	sb.WriteString(".pf-v5-c-login__container { display: flex; flex-direction: column; align-items: center; gap: 1.5rem; width: 100%; max-width: none; padding: 8vh 1rem 3rem; }\n")
	sb.WriteString("#kc-header { order: 0; grid-area: auto; width: auto; max-width: 100%; }\n")
	// align-self: PatternFly starts the card at the cross-axis start,
	// which in a column is the left edge; the parent theme's blue 4 px
	// band on the card header goes too. The shadow suits light and dark
	// backgrounds alike.
	sb.WriteString(".pf-v5-c-login__main { order: 1; grid-area: auto; align-self: center; width: 100%; max-width: 480px; margin: 0; border-radius: 14px; overflow: hidden; box-shadow: 0 8px 24px rgba(0, 0, 0, 0.16); }\n")
	sb.WriteString(".pf-v5-c-login__main-header { border-top: 0; }\n")
	// The header is a column: logo, text, claim. No height on the
	// wrapper: it clipped the title under the logo (write-up 13).
	sb.WriteString("#kc-header-wrapper { display: flex; flex-direction: column; align-items: center; gap: 0.7rem; padding: 0; text-transform: none; letter-spacing: normal; color: var(--portico-text) !important; font-family: \"RedHatDisplay\", \"Helvetica Neue\", Arial, sans-serif; font-weight: 300; }\n")
	if h := b.Header(); h.Logo {
		// The logo is a background so any image type works (write-up
		// 13); its box is computed from the image (header.go).
		fmt.Fprintf(&sb, ".portico-logo { display: block; width: %dpx; height: %dpx; max-width: 100%%; background: url(../img/logo.%s) no-repeat center; background-size: contain; }\n", h.LogoW, h.LogoH, b.LogoFileExt())
	}
	sb.WriteString(".portico-text { font-size: 2.25rem; line-height: 1.1; font-weight: 700; text-align: center; overflow-wrap: anywhere; }\n")
	sb.WriteString(".portico-claim { font-size: 1.05rem; font-weight: 400; opacity: 0.9; text-align: center; }\n")
	sb.WriteString(".pf-v5-c-login__container::after { content: \"Powered by Portico\"; order: 2; margin-top: 1.5rem; color: var(--portico-text); opacity: 0.75; font-size: 0.8rem; padding-left: 1.4rem; background: url(../img/portico-mark.svg) no-repeat left center; background-size: contain; line-height: 1.2rem; }\n")
	sb.WriteString(".pf-v5-c-button.pf-m-primary { background-color: var(--portico-accent); border-color: var(--portico-accent); border-radius: 8px; }\n")
	sb.WriteString(".pf-v5-c-button.pf-m-primary:hover { filter: brightness(1.1); }\n")
	sb.WriteString(".pf-v5-c-form-control { border-radius: 8px; }\n")
	sb.WriteString("a, .pf-v5-c-button.pf-m-link { color: var(--portico-accent); }\n")
	// Keycloak's SAML post page, shown while the assertion goes to Prism
	// Central, looks like Portico's landing page that follows it: no
	// card, a spinner, the text centred (write-up 23).
	const samlPost = `body[data-page-id="login-saml-post-form"]`
	sb.WriteString(samlPost + " .pf-v5-c-login__main { background: none; box-shadow: none; }\n")
	sb.WriteString(samlPost + " .pf-v5-c-login__main-header { display: none; }\n")
	sb.WriteString(samlPost + " .pf-v5-c-login__main-body { text-align: center; color: var(--portico-text); }\n")
	sb.WriteString(samlPost + " .pf-v5-c-login__main-body::before { content: \"\"; display: block; width: 36px; height: 36px; margin: 0 auto 1rem; border: 4px solid color-mix(in srgb, var(--portico-text) 35%, transparent); border-top-color: var(--portico-text); border-radius: 50%; animation: portico-spin 1s linear infinite; }\n")
	sb.WriteString("@keyframes portico-spin { to { transform: rotate(360deg); } }\n")
	return sb.String()
}

// themeMessages sets the texts of the login page. loginTitleHtml renders
// HTML: the header's pieces (logo block, text, claim), each text
// HTML-escaped. loginTitle is the tab title, from the MSP name (the
// realm's display name is fixed at bootstrap). Keycloak formats every
// message with Java's MessageFormat, so each value is MessageFormat-
// escaped, then escaped for the properties syntax. The card says
// "Sign in".
func themeMessages(b Branding) string {
	h := b.Header()
	name := strings.TrimSpace(b.MSPName)
	var title strings.Builder
	if h.Logo {
		title.WriteString(`<span class="portico-logo" role="img" aria-label="` + html.EscapeString(name) + `"></span>`)
	}
	if h.Text != "" {
		title.WriteString(`<span class="portico-text">` + html.EscapeString(h.Text) + `</span>`)
	}
	if claim := strings.TrimSpace(b.Tagline); claim != "" {
		title.WriteString(`<span class="portico-claim">` + html.EscapeString(claim) + `</span>`)
	}
	msg := func(v string) string { return PropertiesEscape(messageFormatEscape(v)) }
	return "loginTitleHtml=" + msg(title.String()) + "\n" +
		"loginTitle=" + msg("Sign in to "+name) + "\n" +
		"loginAccountTitle=Sign in\n" +
		"saml.post-form.title=Signing you in\n" +
		"saml.post-form.message=Signing you in\\u2026\n"
}

// messageFormatEscape quotes what Java's MessageFormat would read as
// syntax: a single quote becomes two, a brace is quoted.
func messageFormatEscape(s string) string {
	return strings.NewReplacer("'", "''", "{", "'{'", "}", "'}'").Replace(s)
}

// PropertiesEscape escapes a value for a Java .properties file: backslash,
// newline, carriage return, tab, leading spaces, "=", ":" and "#" are
// escaped; non-ASCII stays (Keycloak reads UTF-8).
func PropertiesEscape(s string) string {
	var sb strings.Builder
	for i, r := range s {
		switch r {
		case '\\':
			sb.WriteString(`\\`)
		case '\n':
			sb.WriteString(`\n`)
		case '\r':
			sb.WriteString(`\r`)
		case '\t':
			sb.WriteString(`\t`)
		case '=', ':', '#', '!':
			sb.WriteByte('\\')
			sb.WriteRune(r)
		case ' ':
			if i == 0 || strings.TrimSpace(s[:i]) == "" {
				sb.WriteString(`\ `)
			} else {
				sb.WriteByte(' ')
			}
		default:
			sb.WriteRune(r)
		}
	}
	return sb.String()
}
